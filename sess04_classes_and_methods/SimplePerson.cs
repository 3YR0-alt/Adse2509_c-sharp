using System;

namespace sess04_classes_and_methods
{
    /// <summary>
    /// Represents a person and stores their basic personal details including their names, date of birth, binary gender and nationality.
    /// </summary>
    public class SimplePerson
    {
        /// <summary>
        /// Stores the person's full names
        /// </summary>
        protected string names;
        /// <summary>
        /// Stores the person's date of birth
        /// </summary>
        protected DateTime birthDate;
        /// <summary>
        /// Stores the person's binary gender (male or female)
        /// </summary>
        protected string gender;
        /// <summary>
        /// Stores the person's nationality
        /// </summary>
        protected string nationality;

        

    }
}
